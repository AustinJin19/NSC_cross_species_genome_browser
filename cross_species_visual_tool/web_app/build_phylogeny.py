#!/usr/bin/env python3
"""Build the browser's PGLS covariance from the downloaded TimeTree 6 tree.

Rebuild only: requires Biopython and numpy. The browser uses generated files
and does not require a Python/R phylogenetics dependency at runtime.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path

import numpy as np
from Bio import Phylo
from Bio.Phylo.BaseTree import Clade, Tree

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parents[1]


def build(source, selected_tree, destination=HERE):
    original = Phylo.read(source, 'newick')
    previous = Phylo.read(selected_tree, 'newick')
    selected = {t.name for t in previous.get_terminals()} | {'Balaena_mysticetus'}
    tips = {t.name: t for t in original.get_terminals() if t.name in selected}
    if set(tips) != selected:
        raise ValueError(f'Missing TimeTree species: {selected-set(tips)}')
    ancestor = original.common_ancestor([tips[n] for n in sorted(selected)])

    def prune(node):
        if node.is_terminal():
            return Clade(branch_length=node.branch_length, name=node.name) if node.name in selected else None
        children = [v for c in node.clades if (v := prune(c)) is not None]
        if not children:
            return None
        if len(children) == 1:
            children[0].branch_length = (children[0].branch_length or 0)+(node.branch_length or 0)
            return children[0]
        return Clade(branch_length=node.branch_length, name=node.name, clades=children)

    root = prune(ancestor)
    root.branch_length = None
    tree = Tree(root=root, rooted=True)
    names = sorted(selected)
    depths = tree.depths()
    by_name = {t.name: t for t in tree.get_terminals()}
    covariance = np.asarray([[depths[tree.common_ancestor(by_name[a], by_name[b])]
                              for b in names] for a in names])
    assert np.allclose(covariance, covariance.T)
    assert np.ptp(np.diag(covariance)) < 1e-7
    np.linalg.cholesky(covariance)  # Fail on singular branch structure; never add jitter.
    max_distance_error = 0
    for a in previous.get_terminals():
        for b in previous.get_terminals():
            max_distance_error = max(max_distance_error, abs(tree.distance(a.name,b.name)-previous.distance(a,b)))
    assert max_distance_error < 1e-7
    payload = {
        'version': 1,
        'source': 'TimeTree 6 mammal tree',
        'source_url': 'https://timetree.org/downloads/biodiversity/TT6_Mammals.nwk',
        'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
        'date': '2026-10-27',
        'branch_length_unit': 'million years',
        'species': [n.replace('_',' ') for n in names],
        'covariance': covariance.tolist(),
        'definition': 'C_ij = root-to-MRCA shared branch length; C_ii = root-to-tip length. Root is MRCA of the 35 bundled taxa.',
        'lambda_transform': 'Off-diagonal covariance multiplied by lambda; diagonals unchanged.',
        'added_to_existing_34_species_tree': ['Balaena mysticetus'],
        'species_substitutions': [],
        'maximum_previous_tree_distance_error': max_distance_error,
    }
    destination = Path(destination)
    (destination/'data').mkdir(parents=True,exist_ok=True)
    (destination/'www').mkdir(parents=True,exist_ok=True)
    Phylo.write(tree, destination/'data/timetree_pgls.nwk','newick',format_branch_length='%.8f')
    (destination/'data/phylogenetic_covariance.json').write_text(json.dumps(payload,indent=2)+'\n')
    (destination/'www/phylogeny.js').write_text(
        '// Generated by build_phylogeny.py. Do not edit the matrix by hand.\n'
        'const NSCPhylogeny = '+json.dumps(payload,separators=(',',':'))+';\n'
        "if(typeof module!=='undefined')module.exports=NSCPhylogeny;\n")
    print(f'Built covariance for {len(names)} exact TimeTree taxa; existing 34-species distances preserved.')


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,default=PROJECT/'outputs/timetree_34_species_2026-10-27/sources/TT6_Mammals.nwk')
    parser.add_argument('--selected-tree',type=Path,default=PROJECT/'outputs/timetree_34_species_2026-10-27/timetree_34_species.nwk')
    parser.add_argument('--destination',type=Path,default=HERE)
    args=parser.parse_args()
    build(args.source,args.selected_tree,args.destination)
