library(ape)
library(caper)
library(jsonlite)
arg<-grep('^--file=',commandArgs(),value=TRUE)
here<-dirname(normalizePath(sub('^--file=','',arg[1])))
app<-normalizePath(file.path(here,'../../cross_species_visual_tool/web_app'))
tree<-read.tree(file.path(app,'data/timetree_pgls.nwk'))
fits<-fromJSON(file.path(here,'real_data_fits.json'),simplifyVector=FALSE)
rows<-lapply(fits,function(case){
 d<-do.call(rbind,lapply(case$points,as.data.frame)); d$species<-gsub(' ','_',d$species);d$logLength<-log10(d$lengthKb)
 f<-reformulate(c('x',if(case$options$adjustLength)'logLength',if(case$options$adjustMass)'logMass'),response='y')
 cd<-comparative.data(tree,d,names.col='species',vcv=TRUE,na.omit=FALSE)
 fit<-pgls(f,cd,lambda=case$options$lambda,bounds=list(lambda=c(0,1)))
 s<-summary(fit);co<-s$coefficients
 expected<-c(slope=co['x',1],slopeSE=co['x',2],p=co['x',4],lambda=unname(fit$param['lambda']),rSquared=s$r.squared)
 observed<-unlist(case$result[names(expected)])
 error<-max(abs(expected-observed));stopifnot(error<2e-5)
 data.frame(model=case$name,n=nrow(d),MLS_coefficient=expected['slope'],SE=expected['slopeSE'],p=expected['p'],lambda=expected['lambda'],GLS_R2=expected['rSquared'],max_absolute_difference=error,row.names=NULL)
})
result<-do.call(rbind,rows)
write.table(result,file.path(here,'SIRT6_PGLS_validation.tsv'),sep='\t',quote=FALSE,row.names=FALSE)
print(result,digits=6,row.names=FALSE)
cat('\nAll',nrow(result),'real-data fits agree with caper::pgls within 0.00002.\n')
